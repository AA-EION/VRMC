/**
 * Turning a staged build into a WiX file manifest.
 *
 * Split out from build.mjs so it can be tested without WiX installed. It is
 * the part most likely to be quietly wrong: the addons bring a nested
 * directory tree, and a bug here produces an installer that builds cleanly and
 * ships without the MIDI binding in it.
 */
import { readdir } from 'node:fs/promises';
import { join } from 'node:path';

/** Every file under `dir`, as paths relative to it. */
export async function walk(dir, prefix = '') {
  const out = [];
  for (const entry of await readdir(join(dir, prefix), { withFileTypes: true })) {
    const rel = prefix === '' ? entry.name : `${prefix}/${entry.name}`;
    if (entry.isDirectory()) out.push(...(await walk(dir, rel)));
    else out.push(rel);
  }
  return out;
}

function xmlEscape(text) {
  return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

/**
 * Turn the staged tree into a WiX fragment.
 *
 * One component per file, each with its own generated GUID, which is what lets
 * an upgrade replace files individually and an uninstall remove exactly what it
 * installed. Directories are declared as they are first needed.
 */
export function buildFragment(files) {
  const directories = new Map();
  directories.set('', 'INSTALLFOLDER');

  /** Declare a directory and its parents, returning its WiX id. */
  const directoryId = (path) => {
    if (directories.has(path)) return directories.get(path);
    const parent = path.includes('/') ? path.slice(0, path.lastIndexOf('/')) : '';
    const parentId = directoryId(parent);
    const id = `dir_${path.replace(/[^a-zA-Z0-9]/g, '_')}`;
    directories.set(path, id);
    nested.push({ id, parentId, name: path.slice(path.lastIndexOf('/') + 1) });
    return id;
  };

  const nested = [];
  const components = [];

  for (const [index, file] of files.entries()) {
    const dir = file.includes('/') ? file.slice(0, file.lastIndexOf('/')) : '';
    const id = directoryId(dir);
    components.push({
      id: `cmp_${index}`,
      directory: id,
      source: file,
      // KeyPath on the file itself: the installer then tracks each file's own
      // version and replaces it only when it has actually changed.
      name: file.slice(file.lastIndexOf('/') + 1),
    });
  }

  const dirXml = (parentId) =>
    nested
      .filter((d) => d.parentId === parentId)
      .map(
        (d) =>
          `      <Directory Id="${d.id}" Name="${xmlEscape(d.name)}">\n${dirXml(d.id)}      </Directory>\n`,
      )
      .join('');

  return `<?xml version="1.0" encoding="UTF-8"?>
<!--
  Generated by build/installer/build.mjs from the staged Windows build.
  Do not edit: it is rewritten on every release.
-->
<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">
  <Fragment>
    <DirectoryRef Id="INSTALLFOLDER">
${dirXml('INSTALLFOLDER')}    </DirectoryRef>

    <ComponentGroup Id="BridgeFiles">
${components
  .map(
    (c) =>
      `      <Component Id="${c.id}" Directory="${c.directory}" Guid="*">\n` +
      `        <File Id="file_${c.id}" Source="$(var.SourceDir)\\${c.source.replace(/\//g, '\\')}" KeyPath="yes" />\n` +
      `      </Component>`,
  )
  .join('\n')}
    </ComponentGroup>
  </Fragment>
</Wix>
`;
}
